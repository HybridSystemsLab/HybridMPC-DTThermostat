function ok = validTriple(x, u, d)
%VALIDTRIPLE Validate a finite real state [z;q] and scalar input/disturbance.
% q must be binary. Individual set checks impose the required value of u.
ok = isnumeric(x) && isreal(x) && numel(x) == 2 && all(isfinite(x(:))) ...
    && (x(2) == 0 || x(2) == 1) ...
    && isnumeric(u) && isreal(u) && isscalar(u) && isfinite(u) ...
    && isnumeric(d) && isreal(d) && isscalar(d) && isfinite(d);
end
